package t_05_operators;

public class Operators {

    public static void main(String[] args) {

        // =========== Operators ================

// 🔹 Assignment:
//
// =


// 🔹 Compound Assignment:
//
// +=
// -=
// *=
// /=
// %=


// 🔹 Arithmetic Operators:
//
// +  -  *  /  %
//
// Java does not have ** for exponents.
// Use Math.pow(5, 2) instead.
//
// Modulo:
//
// int num1 = 5;
// int num2 = 13;
// int remainder = num2 % num1;
//
// System.out.println(remainder); // 3


// 🔹 Increment and Decrement:
//
// ++ and -- increase or decrease a variable by 1.
//
// x = x + 1;  is the same as  x++;
// x = x - 1;  is the same as  x--;
//
// a++ → post-increment
// ++a → pre-increment
//
// Example:
//
// int i = 0;
//
// System.out.println(i++); // 0
// System.out.println(i);   // 1
//
// i++ → "Give me the number first (print it), then increment i."
//
// Example:
//
// int i = 0;
//
// System.out.println(++i); // 1
// System.out.println(i);   // 1
//
// ++i → "Increment i first, then give me the number (print it)."


// 🔹 Comparison Operators:
//
// ==
// >
// <
// >=
// <=
// !=
//
// Comparison operators return true or false.
//
// Java does not have strict equality operators like JavaScript
// (=== and !==) because Java is a strongly typed language.
//
// Tip: When you see !, it means "not" or negation of what follows.
// That's why != means "not equal."


// 🔹 Logical Operators:
//
// && → AND
// || → OR
// !  → NOT (negation)


// 🔹 Parentheses:
//
// The use of parentheses in Java and JavaScript is the same.
//
// Even when you know the order of operations, you can use parentheses
// to make an expression clearer.
//
// Example:
//
// var dogAge = ((age - 2) * 4) + 21;


// 🔹 Unary Operators:
//
// A unary operator acts on only one variable or value.
//
// -a  → negation (changes a value to negative)
// +a  → positive (changes a negative value to positive)
// !a  → logical negation
// ++a → increment
// --a → decrement
//
// ++ and -- are also unary operators.

    }
}
