package t_03_concatenation;

public class FormatLearnings {
    public static void main(String[] args) {
        System.out.printf("%-15s %10s %10s%n", "Description", "Amount", "Balance");
        System.out.printf("%-15s $%9.2f %10.2f%n", "Groceries", 25.50, 974.50);
        System.out.printf("%-15s $%9.2f %10.2f%n", "Gas", 40.00, 934.50);
        System.out.print("hello");
        System.out.print("hello");

    }
}
